CREATE TABLE IF NOT EXISTS direct_pool_quote (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  scan_id CHAR(36) NOT NULL,
  instrument_id VARCHAR(32) NOT NULL,
  chain_index VARCHAR(16) NOT NULL,
  pool_id VARCHAR(128) NOT NULL,
  dex VARCHAR(64) NOT NULL,
  direction VARCHAR(32) NOT NULL,
  amount_in_raw VARCHAR(100) NULL,
  amount_out_raw VARCHAR(100) NULL,
  minimum_amount_out_raw VARCHAR(100) NULL,
  price_impact_percent DECIMAL(30,12) NULL,
  network_fee_native_raw VARCHAR(100) NULL,
  network_fee_usdt DECIMAL(50,24) NULL,
  block_number BIGINT UNSIGNED NULL,
  block_hash VARCHAR(66) NULL,
  slot BIGINT UNSIGNED NULL,
  pool_state_fingerprint VARCHAR(160) NULL,
  quoted_at DATETIME(3) NULL,
  request_ms INT UNSIGNED NULL,
  status VARCHAR(24) NOT NULL,
  failure_code VARCHAR(64) NULL,
  failure_reason VARCHAR(500) NULL,
  raw_response LONGTEXT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX ix_direct_quote_instrument_chain_time (instrument_id, chain_index, quoted_at),
  INDEX ix_direct_quote_pool_time (pool_id, quoted_at),
  INDEX ix_direct_quote_scan (scan_id),
  INDEX ix_direct_quote_retention (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS direct_pool_decision (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  scan_id CHAR(36) NOT NULL,
  instrument_id VARCHAR(32) NOT NULL,
  chain_index VARCHAR(16) NOT NULL,
  direction VARCHAR(32) NOT NULL,
  size_usdt DECIMAL(30,12) NOT NULL,
  selected_quote_id BIGINT UNSIGNED NULL,
  cex_book_at DATETIME(3) NULL,
  cex_received_at DATETIME(3) NULL,
  cex_seq_id BIGINT NULL,
  cex_bid DECIMAL(50,24) NULL,
  cex_ask DECIMAL(50,24) NULL,
  cex_vwap DECIMAL(50,24) NULL,
  cex_fee_usdt DECIMAL(50,24) NULL,
  dex_network_fee_usdt DECIMAL(50,24) NULL,
  valuation_inputs JSON NULL,
  gross_profit_usdt DECIMAL(50,24) NULL,
  net_profit_usdt DECIMAL(50,24) NULL,
  roi DECIMAL(30,16) NULL,
  valuation_status VARCHAR(24) NOT NULL,
  decision_status VARCHAR(24) NOT NULL,
  block_reason VARCHAR(500) NULL,
  execution_status VARCHAR(24) NOT NULL DEFAULT 'NOT_EXECUTABLE',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX ix_direct_decision_instrument_chain_time (instrument_id, chain_index, created_at),
  INDEX ix_direct_decision_scan (scan_id),
  INDEX ix_direct_decision_retention (created_at),
  CONSTRAINT fk_direct_decision_quote FOREIGN KEY (selected_quote_id) REFERENCES direct_pool_quote(id) ON DELETE SET NULL
) ENGINE=InnoDB;
