CREATE TABLE IF NOT EXISTS dex_pool_state (
  pool_id VARCHAR(128) NOT NULL PRIMARY KEY,
  inst_id VARCHAR(64) NOT NULL,
  chain_index VARCHAR(16) NOT NULL,
  dex VARCHAR(32) NOT NULL,
  pool_address VARCHAR(64) NOT NULL,
  base_token_symbol VARCHAR(32) NOT NULL,
  base_token_address VARCHAR(64) NOT NULL,
  quote_token_symbol VARCHAR(32) NOT NULL,
  quote_token_address VARCHAR(64) NOT NULL,
  marginal_price DECIMAL(50,24) NULL,
  sqrt_price_raw VARCHAR(100) NULL,
  liquidity_raw VARCHAR(100) NULL,
  source VARCHAR(32) NULL,
  block_number BIGINT UNSIGNED NULL,
  block_hash VARCHAR(66) NULL,
  slot BIGINT UNSIGNED NULL,
  transaction_hash VARCHAR(66) NULL,
  log_index INT UNSIGNED NULL,
  account_data_hash CHAR(64) NULL,
  event_fingerprint VARCHAR(160) NULL,
  finality_status VARCHAR(16) NULL,
  confirmed_block_number BIGINT UNSIGNED NULL,
  observed_at DATETIME(3) NULL,
  updated_at DATETIME(3) NOT NULL,
  status VARCHAR(24) NOT NULL,
  last_error VARCHAR(500) NULL,
  INDEX ix_pool_state_asset (inst_id, chain_index)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS dex_pool_event (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  pool_id VARCHAR(128) NOT NULL,
  source VARCHAR(32) NOT NULL,
  marginal_price DECIMAL(50,24) NULL,
  sqrt_price_raw VARCHAR(100) NOT NULL,
  liquidity_raw VARCHAR(100) NOT NULL,
  block_number BIGINT UNSIGNED NULL,
  block_hash VARCHAR(66) NULL,
  slot BIGINT UNSIGNED NULL,
  transaction_hash VARCHAR(66) NULL,
  log_index INT UNSIGNED NULL,
  account_data_hash CHAR(64) NULL,
  event_fingerprint VARCHAR(160) NOT NULL,
  finality_status VARCHAR(16) NOT NULL,
  observed_at DATETIME(3) NOT NULL,
  UNIQUE KEY uq_pool_event_fingerprint (pool_id, event_fingerprint),
  INDEX ix_pool_event_retention (observed_at),
  INDEX ix_pool_event_pool_time (pool_id, observed_at)
) ENGINE=InnoDB;
